CREATE TABLE offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advertiser_id BIGINT NOT NULL,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    landing_url VARCHAR(2048) NOT NULL,
    niche VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_offers_advertiser_id ON offers(advertiser_id);
CREATE INDEX idx_offers_niche ON offers(niche);

CREATE TABLE offer_tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE offer_tag_links (
    offer_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,
    PRIMARY KEY (offer_id, tag_id),
    CONSTRAINT fk_offer_tag_links_offer FOREIGN KEY (offer_id) REFERENCES offers(id) ON DELETE CASCADE,
    CONSTRAINT fk_offer_tag_links_tag FOREIGN KEY (tag_id) REFERENCES offer_tags(id) ON DELETE CASCADE
);

CREATE TABLE campaigns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    budget NUMERIC(12,2) NOT NULL CHECK (budget > 0),
    payout_model VARCHAR(30) NOT NULL,
    payout_value NUMERIC(12,2) NOT NULL CHECK (payout_value >= 0),
    status VARCHAR(20) NOT NULL,
    offer_id BIGINT NOT NULL,
    CONSTRAINT fk_campaigns_offer FOREIGN KEY (offer_id) REFERENCES offers(id) ON DELETE CASCADE,
    CONSTRAINT chk_campaign_dates CHECK (end_date > start_date),
    CONSTRAINT chk_campaign_payout_model CHECK (payout_model IN ('CPC', 'CPL', 'CPA_FIXED', 'CPA_PERCENT')),
    CONSTRAINT chk_campaign_status CHECK (status IN ('DRAFT', 'ACTIVE', 'PAUSED', 'ENDED')),
    CONSTRAINT chk_campaign_payout_value CHECK (
        (payout_model = 'CPA_PERCENT' AND payout_value BETWEEN 0 AND 100)
        OR
        (payout_model IN ('CPC', 'CPL', 'CPA_FIXED') AND payout_value > 0)
    )
);

CREATE INDEX idx_campaigns_offer_id ON campaigns(offer_id);
CREATE INDEX idx_campaigns_status ON campaigns(status);


-- Event publication table used by Spring Modulith's JPA event registry.
CREATE TABLE event_publication (
    id UUID NOT NULL PRIMARY KEY,
    listener_id TEXT NOT NULL,
    event_type TEXT NOT NULL,
    serialized_event TEXT NOT NULL,
    publication_date TIMESTAMP WITH TIME ZONE NOT NULL,
    completion_date TIMESTAMP WITH TIME ZONE,
    status TEXT,
    completion_attempts INTEGER,
    last_resubmission_date TIMESTAMP WITH TIME ZONE
);

-- Database-level protection: at most one ACTIVE campaign per offer.
CREATE UNIQUE INDEX uq_campaign_one_active_per_offer
    ON campaigns(offer_id)
    WHERE status = 'ACTIVE';
